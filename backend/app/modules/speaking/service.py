@dataclass(frozen=True)
class EvaluationInput:
    attempt_id: UUID
    recording_keys: list[str]
    request: SpeakingEvaluationRequest


@dataclass(frozen=True)
class CriterionVerdict:
    code: str
    score: float | None  # None = not assessed
    feedback: str


@dataclass(frozen=True)
class EvaluationResult:
    summary: str
    verdicts: list[CriterionVerdict]


async def prepare_evaluation(db: AsyncSession, job: AIJob) -> EvaluationInput:
    attempt = await db.get(Attempt, job.attempt_id)
    exercise = await db.get(Exercise, attempt.exercise_id)
    evaluation = await db.scalar(
        select(Evaluation).where(Evaluation.attempt_id == attempt.attempt_id)
    )
    evaluation.status = "processing"
    attempt.status = "evaluating"
    session = await session_for(db, attempt.attempt_id)
    rows = (
        await db.execute(
            select(ConversationMessage, MediaAsset)
            .outerjoin(MediaAsset, MediaAsset.media_id == ConversationMessage.audio_media_id)
            .where(
                ConversationMessage.conversation_session_id == session.conversation_session_id,
                ConversationMessage.delivery_status == "ready",
            )
            .order_by(ConversationMessage.position)
        )
    ).all()
    snapshot = evaluation.rubric_snapshot
    return EvaluationInput(
        attempt_id=attempt.attempt_id,
        recording_keys=[
            asset.storage_key
            for message, asset in rows
            if message.sender == "user" and asset is not None and media.is_available(asset)
        ],
        request=SpeakingEvaluationRequest(
            title=exercise.title,
            instructions=exercise.instructions,
            cefr_level=exercise.content_cefr_level,
            turns=[ConversationTurn(sender=m.sender, text=m.transcript) for m, _ in rows],
            recordings=[],
            criteria=[
                SpeakingCriterion(
                    code=c["code"],
                    name=c["name"],
                    descriptor=c["descriptor"],
                    requires_audio=c.get("requires_audio", False),
                )
                for c in snapshot["criteria"]
            ],
            score_min=snapshot["scale"]["min"],
            score_max=snapshot["scale"]["max"],
            score_step=snapshot["scale"]["step"],
        ),
    )


def validate_evaluation(
    request: SpeakingEvaluationRequest, result: SpeakingEvaluation, audio_assessed: bool
) -> EvaluationResult:
    """Untrusted output. Audio criteria without real audio assessment are forced to
    not_assessed, whatever the model claims; a missing criterion is invalid output."""
    by_code = {r.code: r for r in result.criteria}
    if len(by_code) != len(result.criteria) or set(by_code) != {c.code for c in request.criteria}:
        raise _invalid()
    if not result.summary.strip():
        raise _invalid()
    verdicts = []
    for criterion in request.criteria:
        item = by_code[criterion.code]
        if criterion.requires_audio and not audio_assessed:
            verdicts.append(CriterionVerdict(criterion.code, None, rubric.NOT_ASSESSED))
        elif item.assessed:
            if (
                item.score is None
                or not rubric.is_valid_band(item.score)
                or not item.feedback.strip()
            ):
                raise _invalid()
            verdicts.append(CriterionVerdict(criterion.code, item.score, item.feedback.strip()))
        else:
            reason = item.feedback.strip() or rubric.NOT_ASSESSED
            verdicts.append(CriterionVerdict(criterion.code, None, reason))
    return EvaluationResult(result.summary.strip(), verdicts)


async def execute_evaluation(
    engine: AIEngine, data: EvaluationInput, *, store: MediaStore
) -> EvaluationResult:
    recordings: list[bytes] = []
    if engine.assesses_audio:
        for key in data.recording_keys:
            try:
                recordings.append(await asyncio.to_thread(store.read, key))
            except FileNotFoundError:
                continue  # expired/removed audio is simply not assessed
    result = await engine.evaluate_speaking(
        data.request.model_copy(update={"recordings": recordings})
    )
    return validate_evaluation(data.request, result, engine.assesses_audio and bool(recordings))


async def publish_evaluation(
    db: AsyncSession, engine: AIEngine, data: EvaluationInput, result: EvaluationResult
) -> dict:
    evaluation = await db.scalar(
        select(Evaluation)
        .where(Evaluation.attempt_id == data.attempt_id)
        .execution_options(populate_existing=True)
    )
    max_band = Decimal(str(rubric.SCORE_MAX))
    for verdict in result.verdicts:
        assessed = verdict.score is not None
        db.add(
            CriterionResult(
                evaluation_id=evaluation.evaluation_id,
                criterion_code=verdict.code,
                assessment_status="assessed" if assessed else "not_assessed",
                score=Decimal(str(verdict.score)) if assessed else None,
                max_score=max_band if assessed else None,
                feedback=verdict.feedback,
            )
        )
    scores = [v.score for v in result.verdicts]
    complete = all(score is not None for score in scores)
    limitations = [rubric.DISCLAIMER]
    if not complete:
        limitations.append(rubric.OVERALL_MISSING)
    if engine.is_fake:
        limitations.append(FAKE_LIMITATION)
    evaluation.status = "completed"
    evaluation.completed_at = func.now()
    evaluation.overall_score = rubric.overall_band(scores) if complete else None
    evaluation.max_score = max_band if complete else None
    evaluation.summary = result.summary
    evaluation.model_version = engine.name
    evaluation.feedback_payload = {
        "schema_version": 1,
        "corrections": [],
        "limitations": limitations,
    }
    await db.execute(
        update(Attempt)
        .where(Attempt.attempt_id == data.attempt_id)
        .values(
            status="completed",
            current_stage="results",
            completed_at=func.now(),
            last_activity_at=func.now(),
        )
    )
    return {"attempt_id": data.attempt_id, "evaluation_id": evaluation.evaluation_id}


