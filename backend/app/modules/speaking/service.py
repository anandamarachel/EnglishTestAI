"""Speaking: persona conversations by recorded voice turns, then rubric feedback.

Flow: starting an attempt opens one conversation and queues the persona's greeting
(start_conversation). Each recorded turn is validated, stored privately and queued as
process_voice_turn: speech-to-text, a reply from the persona using only successful
earlier messages as context, then TTS of the reply. A session has at most one active
voice job; positions are allocated under the exercise lock. Finishing ends the session
and queues evaluate_attempt over the successful turns and their original recordings.

Criteria that need audio (fluency, pronunciation) are only assessed by an engine that
declares a verified audio assessor; otherwise they are not_assessed and the overall band
stays empty. A transcript never stands in for audio.
"""

