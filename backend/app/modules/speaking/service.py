async def conversation_out(db: AsyncSession, attempt_id: UUID) -> ConversationOut | None:
    session = await session_for(db, attempt_id)
    if session is None:
        return None
    active = await active_voice_job(db, attempt_id)
    return ConversationOut(
        conversation_session_id=session.conversation_session_id,
        attempt_id=attempt_id,
        status=session.status,
        last_activity_at=session.last_activity_at,
        ended_at=session.ended_at,
        active_job=await jobs.to_out(db, active) if active else None,
    )


async def message_out(db: AsyncSession, message: ConversationMessage) -> MessageOut:
    audio = await db.get(MediaAsset, message.audio_media_id) if message.audio_media_id else None
    return MessageOut(
        message_id=message.message_id,
        sender=message.sender,
        position=message.position,
        client_message_key=message.client_message_key,
        reply_to_message_id=message.reply_to_message_id,
        transcript=message.transcript,
        audio=media.to_out(audio) if audio else None,
        transcription_status=message.transcription_status,
        delivery_status=message.delivery_status,
        created_at=message.created_at,
    )


async def list_messages(
    db: AsyncSession, user_id: UUID, attempt_id: UUID, limit: int, cursor: str | None
) -> tuple[list[MessageOut], str | None]:
    session = await session_for(db, attempt_id)
    scope = scope_fingerprint("messages", user_id, attempt_id)
    after = decode_cursor(cursor, scope, 1)
    query = select(ConversationMessage).where(
        ConversationMessage.conversation_session_id == session.conversation_session_id
    )
    if after is not None:
        if not isinstance(after[0], int):
            raise validation_error("cursor", "Cursor is invalid.")
        query = query.where(ConversationMessage.position > after[0])
    rows = list(await db.scalars(query.order_by(ConversationMessage.position).limit(limit + 1)))
    next_cursor = None
    if len(rows) > limit:
        rows = rows[:limit]
        next_cursor = encode_cursor(scope, [rows[-1].position])
    return [await message_out(db, m) for m in rows], next_cursor
